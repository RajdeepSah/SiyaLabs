/**
 * One-off brand pipeline, step 2: build every logo asset from the traced mark.
 *
 *   - Wordmark "Siya Labs" in Sora Bold (700) converted to outlines, laid out
 *     to reproduce the reference lockup (design/siya-labs-brand-reference.png):
 *     same cap height, baseline, gap and tracking (-0.03em, calibrated).
 *   - src/components/brand/logo.json  (inline SVG data for components)
 *   - public/brand/*.svg               (downloadable logo files)
 *   - public/favicon.svg, favicon.ico, apple-touch-icon.png, icon-*.png
 *
 * Run after trace-logo.mjs:  npm run brand:build
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { Resvg } from '@resvg/resvg-js';
import opentypeModule from 'opentype.js';
const opentype = opentypeModule.parse ? opentypeModule : opentypeModule.default;

const ROOT = path.resolve(import.meta.dirname, '..');
const PINE = '#173631';
const IVORY = '#F7F3EA';
const TERRACOTTA = '#A74934';

const mark = JSON.parse(await fs.readFile(path.join(ROOT, 'src/components/brand/mark.json'), 'utf8'));
const [, , MW, MH] = mark.viewBox;
const [MX, MY] = mark.referenceOrigin; // mark top-left inside the reference sheet

/* ------------------------------------------------------------------ */
/* Wordmark outlines                                                    */
/* ------------------------------------------------------------------ */
const fontBuf = await fs.readFile(path.join(ROOT, 'node_modules/@fontsource/sora/files/sora-latin-700-normal.woff'));
const font = opentype.parse(fontBuf.buffer.slice(fontBuf.byteOffset, fontBuf.byteOffset + fontBuf.byteLength));

// Reference measurements (sheet pixels), see design/siya-labs-brand-reference.png
const REF = {
  capHeight: 111, // ink height of "L"
  baseline: 564, // bottom edge of the "L" foot
  inkLeft: 347, // left ink edge of "S"
};
const TRACKING = -30; // font units (= -0.03em), calibrated against the reference
const TEXT = 'Siya Labs';

const L = font.charToGlyph('L').getBoundingBox();
const fontSize = (REF.capHeight / (L.y2 - L.y1)) * font.unitsPerEm;
const scale = fontSize / font.unitsPerEm;

const glyphs = font.stringToGlyphs(TEXT);
const firstInk = glyphs[0].getBoundingBox().x1 * scale;
let penX = REF.inkLeft - firstInk;
let wordmarkD = '';
let inkRight = 0;
glyphs.forEach((g, k) => {
  const p = g.getPath(penX, REF.baseline, fontSize);
  wordmarkD += p.toPathData(1);
  const bb = g.getBoundingBox();
  if (TEXT[k] !== ' ') inkRight = penX + bb.x2 * scale;
  let adv = g.advanceWidth;
  if (k < glyphs.length - 1) adv += font.getKerningValue(g, glyphs[k + 1]);
  penX += (adv + TRACKING) * scale;
});

// Shift everything so the lockup's top-left is the mark's top-left.
function translatePath(d, dx, dy) {
  // opentype emits absolute M/L/Q/C/Z commands.
  return d.replace(/([MLQCZ])([^MLQCZ]*)/g, (_, cmd, args) => {
    if (cmd === 'Z') return 'Z';
    const nums = args.trim().split(/[\s,]+/).filter(Boolean).map(Number);
    const moved = nums.map((n, i) => +(n + (i % 2 === 0 ? dx : dy)).toFixed(1));
    return cmd + moved.join(' ');
  });
}
const wordmark = translatePath(wordmarkD, -MX, -MY);
const LW = +(inkRight - MX).toFixed(1);
const LH = MH;

const logo = {
  note: 'Generated by scripts/build-brand.mjs. Do not edit by hand.',
  viewBox: [0, 0, LW, LH],
  mark: mark.paths,
  markViewBox: mark.viewBox,
  wordmark,
  wordmarkBox: {
    x: +(REF.inkLeft - MX).toFixed(1),
    capTop: +(REF.baseline - REF.capHeight - MY).toFixed(1),
    baseline: +(REF.baseline - MY).toFixed(1),
  },
};
await fs.writeFile(path.join(ROOT, 'src/components/brand/logo.json'), JSON.stringify(logo, null, 2) + '\n');

/* ------------------------------------------------------------------ */
/* SVG files                                                            */
/* ------------------------------------------------------------------ */
const markPaths = (fill) => `<path fill="${fill}" d="${mark.paths.upper}"/><path fill="${fill}" d="${mark.paths.lower}"/>`;

const lockupSvg = (fill, title) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${LW} ${LH}" role="img" aria-labelledby="t"><title id="t">${title}</title>${markPaths(fill)}<path fill="${fill}" d="${wordmark}"/></svg>\n`;

const markSvg = (fill) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${MW} ${MH}" role="img" aria-labelledby="t"><title id="t">Siya Labs</title>${markPaths(fill)}</svg>\n`;

// App icon: terracotta tile, ivory mark at 61.3% of the tile height (as in the reference).
function tileSvg({ size = 512, radius = 0.165, markRatio = 0.613, bg = TERRACOTTA, fg = IVORY } = {}) {
  const h = size * markRatio;
  const s = h / MH;
  const w = MW * s;
  const tx = (size - w) / 2;
  const ty = (size - h) / 2;
  const rx = +(size * radius).toFixed(1);
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}"><rect width="${size}" height="${size}" rx="${rx}" fill="${bg}"/><g transform="translate(${tx.toFixed(2)} ${ty.toFixed(2)}) scale(${s.toFixed(5)})">${markPaths(fg)}</g></svg>\n`;
}

const brandDir = path.join(ROOT, 'public/brand');
await fs.mkdir(brandDir, { recursive: true });
const files = {
  'siya-labs-logo.svg': lockupSvg(PINE, 'Siya Labs'),
  'siya-labs-logo-reversed.svg': lockupSvg(IVORY, 'Siya Labs'),
  'siya-labs-mark.svg': markSvg(PINE),
  'siya-labs-mark-reversed.svg': markSvg(IVORY),
  'siya-labs-app-icon.svg': tileSvg(),
};
for (const [name, svg] of Object.entries(files)) await fs.writeFile(path.join(brandDir, name), svg);
await fs.writeFile(path.join(ROOT, 'public/favicon.svg'), tileSvg());

/* ------------------------------------------------------------------ */
/* Raster icons                                                         */
/* ------------------------------------------------------------------ */
const png = (svg, size) => new Resvg(svg, { fitTo: { mode: 'width', value: size } }).render().asPng();
const pub = (f) => path.join(ROOT, 'public', f);

await fs.writeFile(pub('icon-192.png'), png(tileSvg(), 192));
await fs.writeFile(pub('icon-512.png'), png(tileSvg(), 512));
await fs.writeFile(path.join(brandDir, 'siya-labs-app-icon.png'), png(tileSvg(), 512));
// iOS applies its own mask: full-bleed square, no transparency.
await fs.writeFile(pub('apple-touch-icon.png'), png(tileSvg({ radius: 0 }), 180));
// Android maskable: full bleed, mark inside the 80% safe circle.
await fs.writeFile(pub('icon-maskable-512.png'), png(tileSvg({ radius: 0, markRatio: 0.55 }), 512));

// favicon.ico with embedded PNGs (16, 32, 48).
const icoSizes = [16, 32, 48];
const icoImages = icoSizes.map((s) => png(tileSvg(), s));
const header = Buffer.alloc(6);
header.writeUInt16LE(0, 0);
header.writeUInt16LE(1, 2);
header.writeUInt16LE(icoImages.length, 4);
let offset = 6 + 16 * icoImages.length;
const entries = icoImages.map((img, i) => {
  const e = Buffer.alloc(16);
  e.writeUInt8(icoSizes[i], 0);
  e.writeUInt8(icoSizes[i], 1);
  e.writeUInt8(0, 2);
  e.writeUInt8(0, 3);
  e.writeUInt16LE(1, 4);
  e.writeUInt16LE(32, 6);
  e.writeUInt32LE(img.length, 8);
  e.writeUInt32LE(offset, 12);
  offset += img.length;
  return e;
});
await fs.writeFile(pub('favicon.ico'), Buffer.concat([header, ...entries, ...icoImages]));

// Preview sheet for visual QA (not shipped).
const preview = `<svg xmlns="http://www.w3.org/2000/svg" width="1536" height="1024" viewBox="0 0 1536 1024">
  <rect width="1094" height="1024" fill="${IVORY}"/><rect x="1094" width="442" height="1024" fill="${PINE}"/>
  <g transform="translate(${MX} ${MY})">${markPaths(PINE)}<path fill="${PINE}" d="${wordmark}"/></g>
  <g transform="translate(1183 379) scale(${(267 / 512).toFixed(5)})">${tileSvg().replace(/<\/?svg[^>]*>/g, '')}</g>
</svg>`;
await fs.mkdir(path.join(ROOT, 'design/trace-report'), { recursive: true });
await fs.writeFile(path.join(ROOT, 'design/trace-report/lockup-vs-reference.png'), png(preview, 1536));

console.log(`font-size ${fontSize.toFixed(2)}px, tracking ${TRACKING}u, lockup ${LW} x ${LH} (ratio ${(LW / LH).toFixed(2)})`);
console.log('wordmark path bytes:', wordmark.length);
